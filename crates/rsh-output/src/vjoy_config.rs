//! vJoy device-1 configuration as a general wheel (FH4 fix #1).
//!
//! UWP wheel games (Forza Horizon 4/5, Forza Motorsport on the
//! Store) show no Wheel tab for RSH because of *classification*,
//! not visibility: both RSH devices are generic HID joysticks with
//! no `Windows.Gaming.Input` `RacingWheel` classification. The
//! vJoy half of the fix has two parts — this module is the first:
//! reconfigure vJoy device 1 to the `EmuWheel` envelope (8 axes,
//! 128 buttons, 1× 4-direction POV, all FFB effects enabled), so
//! the device the `GameInput` mapping (written by the installer,
//! see `installer/rsh.nsi`) points at is the wheel-shaped device a
//! `Windows.Gaming.Input` wheel game expects. The mapping is a
//! Windows-level classification, not a per-game hack: no game is
//! detected, no game-specific key is written — any game that reads
//! the `RacingWheel` classification sees the same wheel. The
//! second part — the `1234BEAD00010004` `RacingWheel` registry
//! mapping itself — lives in the installer, not here: it needs
//! admin + HKLM, and the installer is the elevated component.
//!
//! # Why `vJoyConfig.exe`, not a hand-built descriptor
//!
//! A vJoy device's shape is a HID report descriptor blob
//! (`HidReportDescriptor` `REG_BINARY` under
//! `HKLM\SYSTEM\CurrentControlSet\Services\vjoy\Parameters\Device01`)
//! plus an FFB section — generated by vJoy's own config tool from
//! the (axes, buttons, POVs, effects) the user picks. Rebuilding
//! that descriptor by hand in RSH would duplicate ~700 bytes of
//! upstream template (`hidReportDescFfb.h`) and drift the moment
//! upstream changes it. vJoy ships a CLI for exactly this:
//! `vJoyConfig.exe` (at `%ProgramFiles%\vJoy\x64\vJoyConfig.exe`,
//! `BrunnerInnovation` vJoy 2.2.2.0, the pinned release) configures a
//! device from the command line and restarts the driver devices
//! afterwards (`refresh_vjoy`), so no reboot is needed in the
//! normal case. Verified against the upstream source
//! (`BrunnerInnovation/vJoy`, `apps/vJoyConf/vJoyConfig/`):
//!
//! ```text
//! vJoyConfig.exe 1 -f -a x y z rx ry rz sl0 sl1 -b 128 -s 1 -e All
//! ```
//!
//! * `1` — target device 1 (RSH's vJoy device; the only one RSH
//!   ever touches).
//! * `-f` — force: delete the current device-1 config first, so a
//!   reinstall / update replaces whatever is there instead of
//!   refusing (`Create` without `-f` fails on an existing device).
//! * `-a x y z rx ry rz sl0 sl1` — the 8 axes. Descriptor order is
//!   fixed upstream (X, Y, Z, Rx, Ry, Rz, Slider0, Slider1, …), so
//!   the `RawGameController` axis array a game reads is X=0, Y=1,
//!   Z=2, Rx=3, Ry=4, Rz=5, Slider=6, Dial=7 — the `GameInput`
//!   mapping in the installer relies on exactly this order
//!   (Wheel=X/0, Throttle=Y/1, Brake=Z/2, Handbrake=Slider/6).
//! * `-b 128` — 128 buttons (the feed already writes buttons
//!   1–128 across `lButtons` / `lButtonsEx1–3`; see `vjoy.rs`).
//! * `-s 1` — one *discrete* (4-direction) POV hat. `-p` would be
//!   a continuous POV; the `EmuWheel` envelope is the 4-direction
//!   one, and RSH feeds no hat input either way (hats stay neutral).
//! * `-e All` — all eleven FFB effects (Const, Ramp, Sq, Sine, Tr,
//!   `StUp`, `StDn`, Spr, Dm, Inr, Fric). FFB lives in the descriptor's
//!   FFB section; without it the device reports no force feedback
//!   and a wheel game has no reason to treat it as a wheel.
//!
//! # Who runs it
//!
//! Two call sites, both best-effort-or-loud (never silent):
//!
//! * The RSH installer (`installer/rsh.nsi`, elevated) runs
//!   `vJoyConfig.exe` directly when vJoy is already installed —
//!   fresh install and update alike (the install section runs on
//!   every install). vJoy missing → skipped: the wizard installs
//!   vJoy later, and the second call site covers that.
//! * [`configure_device_1_envelope`] (Windows-only) is the
//!   in-app path, called after the wizard's vJoy install
//!   (`rsh-app-core`, `run_vjoy_install_inner`). The daemon runs
//!   non-elevated, so this runs `vJoyConfig.exe` elevated via
//!   PowerShell `Start-Process -Verb RunAs` (one UAC prompt — the
//!   vJoy installer itself already prompted once). A declined
//!   prompt, a timeout, or a non-zero exit is a loud failure: the
//!   caller reports it and points at re-running the RSH installer
//!   (which writes the envelope *and* the `GameInput` mapping).
//!
//! # Verification (and its limit)
//!
//! `vJoyConfig.exe` exits 0 even when the registry write fails
//! (upstream `_tmain` ignores the write result), so the exit code
//! only proves the tool ran — it does **not** prove the envelope
//! landed. The real verification is the connect-time capabilities
//! read the vJoy backend already does (`GetVJDAxisExist` /
//! `GetVJDButtonNumber` → [`VJoyCapabilities`](super::vjoy::VJoyCapabilities),
//! validated against the plan by
//! [`validate_capabilities`](super::vjoy::validate_capabilities)):
//! a device 1 without the envelope fails the connect with a named
//! missing capability instead of feeding a wrong-shaped device.
//! The installer additionally checks the descriptor landed by
//! reading back `HidReportDescriptorSize` for `Device01`.
//! The only proof a game shows the Wheel tab is the user's PC
//! retest — in Forza Horizon 4 and in a second game — and nothing
//! here claims the wheel works in every game.

#[cfg(windows)]
use std::env;
use std::fmt;
use std::path::{Path, PathBuf};
#[cfg(windows)]
use std::time::{Duration, Instant};

/// vJoy device id RSH drives (and the only device this module ever
/// configures). The `GameInput` mapping key `1234BEAD00010004` is
/// vJoy device 1's VID/PID (`1234`/`BEAD`).
pub const VJOY_FH4_DEVICE_ID: u32 = 1;
/// File name of vJoy's command-line config tool. Shipped with the
/// driver (never bundled by RSH, same as `vJoyInterface.dll`).
pub const VJOY_CONFIG_EXE_FILE_NAME: &str = "vJoyConfig.exe";
/// The `EmuWheel` envelope's axes, in vJoyConfig `-a` spelling.
/// Descriptor order is fixed upstream (X, Y, Z, Rx, Ry, Rz,
/// Slider0, Slider1), so these are `RawGameController` axes 0–7.
pub const VJOY_FH4_AXES: [&str; 8] = ["x", "y", "z", "rx", "ry", "rz", "sl0", "sl1"];
/// The `EmuWheel` envelope's button count (`-b`).
pub const VJOY_FH4_BUTTONS: i32 = 128;
/// The `EmuWheel` envelope's discrete (4-direction) POV hat count
/// (`-s`). RSH feeds no hat input; the hat exists so the device
/// shape matches the envelope.
pub const VJOY_FH4_DISCRETE_POVS: i32 = 1;
/// The `EmuWheel` envelope's FFB effects (`-e`): all eleven.
pub const VJOY_FH4_FFB_EFFECTS: &str = "All";

/// Registry subkey (under HKLM) where vJoy stores device 1's HID
/// report descriptor — the shape `vJoyConfig.exe` writes. The
/// installer reads back `HidReportDescriptorSize` here to prove
/// the envelope landed; the two-char suffix is the zero-padded
/// device number (`Device01`, not `Device1`).
pub const VJOY_DEVICE1_REGISTRY_SUBKEY: &str =
    r"SYSTEM\CurrentControlSet\Services\vjoy\Parameters\Device01";
/// Value under [`VJOY_DEVICE1_REGISTRY_SUBKEY`] holding the
/// descriptor's byte size (`REG_DWORD`).
pub const VJOY_DESCRIPTOR_SIZE_VALUE: &str = "HidReportDescriptorSize";

/// Everything that can go wrong configuring vJoy device 1.
///
/// Display strings are the human-readable reason: the caller shows
/// them verbatim, so they name the fix ("re-run the RSH installer
/// …"), never just a code.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum VJoyConfigError {
    /// `vJoyConfig.exe` was not found (vJoy not installed, or
    /// installed somewhere unexpected).
    ToolNotFound,
    /// The elevated `vJoyConfig.exe` run could not be started.
    SpawnFailed(String),
    /// The run did not finish within the bound (the UAC prompt
    /// was ignored, or the tool hung) — the child was killed.
    TimedOut,
    /// The run finished but failed (non-zero exit — including a
    /// declined UAC prompt, which PowerShell reports as an error).
    Failed(String),
}

impl fmt::Display for VJoyConfigError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::ToolNotFound => write!(
                f,
                "vJoyConfig.exe was not found — vJoy does not look installed. Install vJoy first, then re-run the RSH installer."
            ),
            Self::SpawnFailed(msg) => {
                write!(f, "could not start the vJoy device-1 configuration: {msg}")
            }
            Self::TimedOut => write!(
                f,
                "configuring vJoy device 1 timed out after {VJOY_CONFIG_TIMEOUT_SECS} s (the UAC prompt may have been ignored) — the change was not applied. Re-run the RSH installer and accept the prompt."
            ),
            Self::Failed(msg) => write!(f, "{msg}"),
        }
    }
}

impl std::error::Error for VJoyConfigError {}

/// The exact `vJoyConfig.exe` argument list for the `EmuWheel`
/// envelope on device 1 (no program name — the caller supplies
/// the resolved exe path).
///
/// `1 -f -a x y z rx ry rz sl0 sl1 -b 128 -s 1 -e All`
/// (see the module docs for what each flag means and where it was
/// verified). Pure, so the installer and the tests share the one
/// spelling — a drift between them would configure a different
/// device than the `GameInput` mapping expects.
#[must_use]
pub fn vjoy_config_argv() -> Vec<String> {
    let mut argv = vec![
        VJOY_FH4_DEVICE_ID.to_string(),
        "-f".to_string(),
        "-a".to_string(),
    ];
    argv.extend(VJOY_FH4_AXES.iter().map(|axis| (*axis).to_string()));
    argv.extend([
        "-b".to_string(),
        VJOY_FH4_BUTTONS.to_string(),
        "-s".to_string(),
        VJOY_FH4_DISCRETE_POVS.to_string(),
        "-e".to_string(),
        VJOY_FH4_FFB_EFFECTS.to_string(),
    ]);
    argv
}

/// Resolve `vJoyConfig.exe` without ever bundling it (same rule as
/// the DLL, D18).
///
/// Order: `%ProgramFiles%\vJoy\x64\...` →
/// `%ProgramFiles(x86)%\vJoy\x64\...`. Returns `None` when vJoy is
/// not installed. Windows-only (the env reads are Windows-only).
#[cfg(windows)]
#[must_use]
pub fn resolve_vjoy_config_path() -> Option<PathBuf> {
    resolve_vjoy_config_path_from_env(
        env::var("ProgramFiles").ok().as_deref(),
        env::var("ProgramFiles(x86)").ok().as_deref(),
    )
}

/// Pure half of [`resolve_vjoy_config_path`]: the `ProgramFiles`
/// candidates for explicit base directories (testable on any OS —
/// no env reads). Mirrors
/// [`resolve_dll_path_from_env`](super::vjoy::resolve_dll_path_from_env).
#[must_use]
pub fn resolve_vjoy_config_path_from_env(
    program_files: Option<&str>,
    program_files_x86: Option<&str>,
) -> Option<PathBuf> {
    for base in [program_files, program_files_x86].into_iter().flatten() {
        let candidate = Path::new(base)
            .join("vJoy")
            .join("x64")
            .join(VJOY_CONFIG_EXE_FILE_NAME);
        if candidate.is_file() {
            return Some(candidate);
        }
    }
    None
}

/// Bound on the elevated `vJoyConfig.exe` run, in seconds (same
/// 120 s bound as the vJoy installer run in `rsh-app-core` — the
/// wait includes the user answering the UAC prompt).
pub const VJOY_CONFIG_TIMEOUT_SECS: u64 = 120;

/// Configure vJoy device 1 to the `EmuWheel` envelope (Windows-only).
///
/// Locates `vJoyConfig.exe` ([`resolve_vjoy_config_path`]) and runs
/// it elevated (`Start-Process -Verb RunAs`, one UAC prompt) with
/// [`vjoy_config_argv`], waiting at most
/// [`VJOY_CONFIG_TIMEOUT_SECS`] seconds. The daemon runs
/// non-elevated, so the elevation is the only way this write
/// (HKLM) can happen from the app; the installer does the same
/// step directly (it is already elevated) and is the primary path.
///
/// # Errors
///
/// [`VJoyConfigError::ToolNotFound`] when vJoy is not installed,
/// [`VJoyConfigError::SpawnFailed`] when the elevated run could
/// not be started, [`VJoyConfigError::TimedOut`] when it did not
/// finish in time (child killed), [`VJoyConfigError::Failed`]
/// when it exited non-zero (including a declined UAC prompt).
///
/// A success only proves the tool ran — `vJoyConfig.exe` exits 0
/// even when its registry write fails (see the module docs). The
/// connect-time capabilities read is the verification.
#[cfg(windows)]
pub fn configure_device_1_envelope() -> Result<(), VJoyConfigError> {
    use std::os::windows::process::CommandExt;
    use std::process::Command;

    let tool = resolve_vjoy_config_path().ok_or(VJoyConfigError::ToolNotFound)?;
    // `-Verb RunAs` elevates (one UAC prompt); `-Wait` blocks the
    // PowerShell child until vJoyConfig exits, so the exit code
    // below is the tool's. The argument list is a single string —
    // none of its tokens contain a space, so no quoting is needed
    // inside it. The exe path can contain spaces (Program Files),
    // so it is double-quoted.
    let args = vjoy_config_argv().join(" ");
    let script = format!(
        "Start-Process -FilePath \"{}\" -ArgumentList \"{args}\" -Verb RunAs -Wait",
        tool.display()
    );
    let mut child = Command::new("powershell.exe")
        .args(["-NoProfile", "-NonInteractive", "-Command", &script])
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .creation_flags(0x0800_0000) // CREATE_NO_WINDOW
        .spawn()
        .map_err(|error| {
            VJoyConfigError::SpawnFailed(format!("could not run powershell.exe: {error}"))
        })?;
    let deadline = Instant::now() + Duration::from_secs(VJOY_CONFIG_TIMEOUT_SECS);
    loop {
        match child.try_wait() {
            Ok(Some(status)) => {
                if status.success() {
                    return Ok(());
                }
                return Err(VJoyConfigError::Failed(format!(
                    "vJoyConfig.exe failed (exit {}) — the device-1 envelope was not applied. If the UAC prompt was declined, accept it; otherwise re-run the RSH installer, which writes the envelope and the Windows.Gaming.Input RacingWheel mapping together.",
                    status.code().unwrap_or(-1)
                )));
            }
            Ok(None) => {
                if Instant::now() >= deadline {
                    let _ = child.kill();
                    let _ = child.wait();
                    return Err(VJoyConfigError::TimedOut);
                }
                std::thread::sleep(Duration::from_millis(100));
            }
            Err(error) => {
                return Err(VJoyConfigError::Failed(format!(
                    "could not wait for vJoyConfig.exe: {error}"
                )));
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn argv_is_the_exact_emu_wheel_envelope() {
        assert_eq!(
            vjoy_config_argv(),
            vec![
                "1", "-f", "-a", "x", "y", "z", "rx", "ry", "rz", "sl0", "sl1", "-b", "128", "-s",
                "1", "-e", "All",
            ]
        );
    }

    #[test]
    fn argv_targets_device_1_only_and_forces() {
        let argv = vjoy_config_argv();
        assert_eq!(argv[0], VJOY_FH4_DEVICE_ID.to_string());
        assert_eq!(VJOY_FH4_DEVICE_ID, 1);
        assert_eq!(argv[1], "-f");
        // No other device id appears anywhere in the argv.
        assert!(!argv[2..].iter().any(|arg| arg == "2"));
    }

    #[test]
    fn envelope_constants_are_the_emu_wheel_shape() {
        assert_eq!(VJOY_FH4_AXES.len(), 8);
        assert_eq!(
            VJOY_FH4_AXES,
            ["x", "y", "z", "rx", "ry", "rz", "sl0", "sl1"]
        );
        assert_eq!(VJOY_FH4_BUTTONS, 128);
        assert_eq!(VJOY_FH4_DISCRETE_POVS, 1);
        assert_eq!(VJOY_FH4_FFB_EFFECTS, "All");
    }

    #[test]
    fn device1_registry_subkey_is_zero_padded() {
        // vJoyConfig writes Device%02d — device 1 is Device01.
        assert!(VJOY_DEVICE1_REGISTRY_SUBKEY.ends_with("Device01"));
        assert_eq!(VJOY_DESCRIPTOR_SIZE_VALUE, "HidReportDescriptorSize");
    }

    #[test]
    fn resolve_from_env_finds_program_files() {
        let base =
            std::env::temp_dir().join(format!("rsh-vjoycfg-test-{}-resolve", std::process::id()));
        let tool_dir = base.join("vJoy").join("x64");
        std::fs::create_dir_all(&tool_dir).expect("create fake install dir");
        let tool = tool_dir.join(VJOY_CONFIG_EXE_FILE_NAME);
        std::fs::write(&tool, b"fake").expect("write fake vJoyConfig.exe");
        let base_str = base.to_str().expect("temp path is UTF-8");
        assert_eq!(
            resolve_vjoy_config_path_from_env(Some(base_str), None),
            Some(tool)
        );
        // x86 fallback when the x64 ProgramFiles has no tool.
        let x86 = base.join("x86");
        let x86_tool_dir = x86.join("vJoy").join("x64");
        std::fs::create_dir_all(&x86_tool_dir).expect("create fake x86 dir");
        let x86_tool = x86_tool_dir.join(VJOY_CONFIG_EXE_FILE_NAME);
        std::fs::write(&x86_tool, b"fake").expect("write fake x86 tool");
        let empty = base.join("empty");
        let empty_str = empty.to_str().expect("temp path is UTF-8");
        let x86_str = x86.to_str().expect("temp path is UTF-8");
        assert_eq!(
            resolve_vjoy_config_path_from_env(Some(empty_str), Some(x86_str)),
            Some(x86_tool)
        );
        assert_eq!(resolve_vjoy_config_path_from_env(None, None), None);
        assert_eq!(
            resolve_vjoy_config_path_from_env(Some(empty_str), Some(empty_str)),
            None
        );
        let _ = std::fs::remove_dir_all(&base);
    }

    #[test]
    fn config_error_messages_name_the_fix() {
        assert!(
            VJoyConfigError::ToolNotFound
                .to_string()
                .contains("re-run the RSH installer")
        );
        assert!(VJoyConfigError::TimedOut.to_string().contains("UAC"));
        assert!(
            VJoyConfigError::Failed("x".to_string())
                .to_string()
                .contains('x'),
            "Failed carries the detail verbatim"
        );
    }
}
